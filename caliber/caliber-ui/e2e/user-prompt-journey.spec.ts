import { expect, test } from "@playwright/test";

import { signIn } from "./helpers";

/**
 * The alpha's one promise, driven the way a new user would: create a prompt,
 * calibrate it against a test set, review the candidate, apply it, and roll back.
 *
 * `two-week-alpha-journey.spec.ts` covers the same release path, but on a fixture
 * that a user cannot create. This spec uses nothing seeded: the prompt, the test
 * set, the calibration run and the candidate are all created here, on the harness
 * defaults (fake LLM, fake evaluator, real MLflow promoter).
 *
 * One step is done by API rather than through the page. Test cases on the
 * Test Sets stage are generated by the Aria assistant, which needs a real LLM,
 * and this journey runs offline. The dataset endpoint it uses is the same one the
 * page saves to.
 *
 * What it proves, in order:
 *  1. A prompt created in the UI is live as v1.
 *  2. A MetaPrompt calibration run against a 3-example test set reaches a
 *     reviewable candidate.
 *  3. The review dialog says the evaluation is simulated, and reports the real
 *     example count (alpha gap P0-4).
 *  4. Apply registers v2 and makes it live in the MLflow registry (P0-2, P0-3).
 *  5. Rollback makes v1 live again, in the UI and in the registry.
 */
const API = "/ajax-api/2.0/mlflow/caliber";

test.describe("User prompt journey (alpha)", () => {
  test("creates a prompt, calibrates it, applies the candidate and rolls back", async ({
    page,
  }) => {
    test.setTimeout(240_000);
    const suffix = Date.now().toString(36);
    const promptName = `journey-prompt-${suffix}`;
    const datasetName = `journey-set-${suffix}`;

    await signIn(page);

    // ---- 1. Create a prompt in the UI; it is live as v1 --------------------
    await page.goto("/caliber/prompts");
    await page.getByRole("button", { name: "New prompt" }).click();
    await page.getByRole("button", { name: /Write \/ paste/ }).click();
    await page
      .getByLabel("Prompt text")
      .fill(
        "Classify the support ticket as billing, bug or other.\n\nTicket: {ticket}",
      );
    await page.getByLabel("Prompt name").fill(promptName);
    await page.getByRole("button", { name: "Create and Open" }).click();

    const versionPanel = page.getByTestId("version-panel");
    await expect(versionPanel).toBeVisible();
    await expect(page.getByTestId("version-row-1")).toBeVisible();
    await expect(
      page.getByTestId("version-row-1").getByTestId("version-live-badge"),
    ).toBeVisible();

    // ---- 2. A test set with three examples (API; see the header) -----------
    const created = await page.request.post(`${API}/eval-datasets`, {
      data: { name: datasetName, owner: "admin" },
    });
    expect(created.ok(), await created.text()).toBeTruthy();
    const datasetId = (await created.json()).data.dataset_id as string;
    for (const ticket of [
      "I was charged twice this month",
      "The export button crashes the page",
      "How do I change my avatar?",
    ]) {
      const example = await page.request.post(
        `${API}/eval-datasets/${datasetId}/examples`,
        {
          data: { input: { ticket }, expected: { label: "billing" } },
        },
      );
      expect(example.ok(), await example.text()).toBeTruthy();
    }

    // ---- 3. Start a MetaPrompt calibration run from the Calibration stage ---
    await page
      .getByRole("button", { name: "Calibration", exact: true })
      .click();
    await page
      .getByLabel("Calibration dataset", { exact: true })
      .selectOption({ label: datasetName });
    await expect(
      page.getByLabel("Calibration strategy", { exact: true }),
    ).toHaveValue("MetaPrompt");
    await page.getByRole("button", { name: "Start Calibration Run" }).click();

    // The fake LLM and evaluator finish in seconds; give the worker room under CI load.
    const reviewButton = page
      .getByRole("button", { name: "Review & apply" })
      .first();
    await expect(reviewButton).toBeVisible({ timeout: 120_000 });

    // ---- 4. Review: the evidence is labelled simulated and counts the 3 cases
    await reviewButton.click();
    await expect(
      page.getByRole("heading", { name: "Review candidate before applying" }),
    ).toBeVisible();
    await expect(
      page.getByTestId("calibration-simulated-evaluation"),
    ).toContainText("Simulated evaluation — not evidence");
    await expect(page.getByText("3 evaluation examples")).toBeVisible();
    await expect(page.getByText("Gate: Passed")).toBeVisible();

    // ---- 5. Apply: v2 becomes live in the registry -------------------------
    const confirmApply = page.getByRole("button", { name: /Apply candidate/ });
    await expect(confirmApply).toBeEnabled();
    await confirmApply.click();
    await expect(page.getByText(/Candidate applied\./)).toBeVisible({
      timeout: 60_000,
    });

    await page.getByRole("button", { name: "Author", exact: true }).click();
    await expect(page.getByTestId("version-row-2")).toBeVisible();
    await expect(
      page.getByTestId("version-row-2").getByTestId("version-live-badge"),
    ).toBeVisible();
    await expect(
      page.getByTestId("version-row-1").getByTestId("version-live-badge"),
    ).toHaveCount(0);
    await expect
      .poll(async () => liveVersion(page, promptName), { timeout: 20_000 })
      .toBe(2);

    // ---- 6. Roll back: v1 is live again ------------------------------------
    await page
      .getByTestId("version-row-2")
      .getByTestId("version-rollback")
      .click();
    await expect(page.getByTestId("confirm-dialog")).toBeVisible();
    await page.getByTestId("confirm-dialog-confirm").click();
    await expect(page.getByTestId("confirm-dialog")).toBeHidden();

    await expect(
      page.getByTestId("version-row-1").getByTestId("version-live-badge"),
    ).toBeVisible();
    await expect(
      page.getByTestId("version-row-2").getByTestId("version-live-badge"),
    ).toHaveCount(0);
    await expect
      .poll(async () => liveVersion(page, promptName), { timeout: 20_000 })
      .toBe(1);
  });
});

/** The version the registry's `prod` alias points at, read from the API. */
async function liveVersion(
  page: import("@playwright/test").Page,
  promptName: string,
): Promise<number | null> {
  const response = await page.request.get(
    `${API}/prompts/${encodeURIComponent(promptName)}/versions`,
  );
  if (!response.ok()) return null;
  const body = (await response.json()) as {
    data: Array<{ version: number | string; aliases?: string[] }>;
  };
  const rows = body.data;
  const live = rows.find((row) => (row.aliases ?? []).includes("prod"));
  return live ? Number(live.version) : null;
}
