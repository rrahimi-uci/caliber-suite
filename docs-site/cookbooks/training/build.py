def patch_docs_css() -> None:
    css = DOCS_CSS.read_text(encoding="utf-8")
    start = css.find(CSS_MARKER)
    if start != -1:
        css = css[:start].rstrip() + "\n"
    DOCS_CSS.write_text(css.rstrip() + "\n\n" + COOKBOOK_CSS, encoding="utf-8")


