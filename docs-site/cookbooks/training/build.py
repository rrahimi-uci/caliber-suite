def main() -> None:
    # 1. detail pages
    n = len(COOKBOOKS)
    for i, cb in enumerate(COOKBOOKS):
        prev_cb = COOKBOOKS[i - 1] if i > 0 else None
        next_cb = COOKBOOKS[i + 1] if i < n - 1 else None
        body = render_detail_body(cb, prev_cb, next_cb)
        (DOCS_SITE / detail_filename(cb)).write_text(
            page(f"Cookbook {cb['num']}: {cb['title']}", body), encoding="utf-8"
        )
    # 2. index
    INDEX_OUT.write_text(page("Cookbooks", render_index_body()), encoding="utf-8")
    # 3. nav manifest for build-docs.mjs (Overview + one link per cookbook)
    nav = [{"href": "m-16-cookbooks.html", "label": "All cookbooks"}]
    nav += [{"href": detail_filename(cb), "label": f"{cb['num']} · {cb['title']}"} for cb in COOKBOOKS]
    NAV_JSON.write_text(json.dumps(nav, indent=2) + "\n", encoding="utf-8")
    # 4. styles
    patch_docs_css()
    overrides = sum(1 for cb in COOKBOOKS if (f := folder_for(cb["num"])) and (f / "training-steps.json").exists())
    print(f"wrote index + {n} detail pages + cookbooks-nav.json ({overrides} detailed-step overrides) + patched docs.css")


if __name__ == "__main__":
    main()
