"""Render the CALIBER Cookbooks as NATIVE doc-suite pages.

Produces, in ../../docs-site/:
  • m-16-cookbooks.html              — the index (a card per cookbook)
  • m-cookbook-<nn>-<slug>.html      — one self-contained detail page per cookbook
  • cookbooks-nav.json               — {href,label} manifest consumed by build-docs.mjs
and appends cookbook component CSS to docs.css.

Each detail page is fully self-contained for in-app serving:
  • every UI step gets an auto-generated UI **snapshot** (derived from its nav
    path + fields + button),
  • asset files are **inlined** as copyable code blocks with same-page anchors,
    so there are no cross-folder links that 404 when served at /caliber/docs/.

Mermaid + theme come from the doc-suite (docs.css / docs.js / mermaid@11).

    python3 build.py
"""
